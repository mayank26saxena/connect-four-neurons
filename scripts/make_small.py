"""Write configs/small/s<seed>.yaml (3 layers, d_model 128; PLAN addendum k) and configs/ladder/L<layers>d<d_model>_s<seed>.yaml
(PLAN addendum l). 4 heads, d_ff = 4 d_model, 6,000 steps, seeds 1-5."""
import copy

import yaml

from c4n import config


def main():
    base = config.load("base")
    out = config.ROOT / "configs" / "small"
    out.mkdir(exist_ok=True)
    for s in range(1, 6):
        c = copy.deepcopy(base)
        c["model"].update(n_layer=3, d_model=128, n_head=4, d_ff=512)
        c["train"].update(steps=6000, seed=s, ckpt_steps=[0, 6000], out_dir=f"checkpoints/small/s{s}")
        c["analysis"]["checkpoint"] = f"checkpoints/small/s{s}/step_006000.pt"
        c["results_dir"] = f"results/small/s{s}"
        (out / f"s{s}.yaml").write_text(f"# generated by scripts/make_small.py: 3 layers, d_model 128, seed {s}\n" + yaml.safe_dump(c, sort_keys=False))
    print(sorted(p.name for p in out.iterdir()))


LADDER = [(1, 64), (1, 128), (2, 64), (2, 128), (3, 64)]
MID = [(6, 128, 4, range(1, 6)), (4, 192, 6, range(1, 6)), (4, 256, 8, range(1, 6)), (6, 256, 8, (2, 3))]  # addendum m


def ladder():
    base = config.load("base")
    out = config.ROOT / "configs" / "ladder"
    out.mkdir(exist_ok=True)
    for nl, d in LADDER:
        for s in range(1, 6):
            name = f"L{nl}d{d}_s{s}"
            c = copy.deepcopy(base)
            c["model"].update(n_layer=nl, d_model=d, n_head=4, d_ff=4 * d)
            c["train"].update(steps=6000, seed=s, ckpt_steps=[0, 6000], out_dir=f"checkpoints/ladder/{name}")
            c["analysis"]["checkpoint"] = f"checkpoints/ladder/{name}/step_006000.pt"
            c["results_dir"] = f"results/ladder/{name}"
            (out / f"{name}.yaml").write_text(f"# generated by scripts/make_small.py --ladder: {nl} layers, d_model {d}, seed {s}\n" + yaml.safe_dump(c, sort_keys=False))
    for nl, d, nh, seeds in MID:
        for s in seeds:
            name = f"L{nl}d{d}_s{s}"
            c = copy.deepcopy(base)
            c["model"].update(n_layer=nl, d_model=d, n_head=nh, d_ff=4 * d)
            c["train"].update(steps=6000, seed=s, ckpt_steps=[0, 6000], out_dir=f"checkpoints/ladder/{name}")
            c["analysis"]["checkpoint"] = f"checkpoints/ladder/{name}/step_006000.pt"
            c["results_dir"] = f"results/ladder/{name}"
            (out / f"{name}.yaml").write_text(f"# generated by scripts/make_small.py --ladder: {nl} layers, d_model {d}, {nh} heads, seed {s}\n" + yaml.safe_dump(c, sort_keys=False))
    print(len(list(out.iterdir())), "ladder configs")


CONCEPT = [("L4d192", 4, 192, 6, (1, 2, 3)), ("L6d128", 6, 128, 4, (1, 2))]  # addendum o


def concept():
    base = config.load("base")
    out = config.ROOT / "configs" / "concept"
    out.mkdir(exist_ok=True)
    for tag, nl, d, nh, seeds in CONCEPT:
        for s in seeds:
            name = f"{tag}_s{s}"
            c = copy.deepcopy(base)
            c["model"].update(n_layer=nl, d_model=d, n_head=nh, d_ff=4 * d)
            c["train"].update(steps=6000, seed=s, ckpt_steps=[0, 6000], out_dir=f"checkpoints/concept/{name}")
            c["analysis"]["checkpoint"] = f"checkpoints/concept/{name}/step_006000.pt"
            c["results_dir"] = f"results/concept/{name}"
            (out / f"{name}.yaml").write_text(f"# generated by scripts/make_small.py --concept: {nl} layers, d_model {d}, seed {s}\n" + yaml.safe_dump(c, sort_keys=False))
    print(len(list(out.iterdir())), "concept configs")


if __name__ == "__main__":
    import sys
    ladder() if "--ladder" in sys.argv else concept() if "--concept" in sys.argv else main()
