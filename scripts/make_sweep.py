"""Write configs/sweep/w<d_ff>_s<seed>.yaml: the base config with one MLP width and one training seed.

Everything else (data, d_model, layers, heads, optimiser, schedule, analysis settings) is inherited unchanged, so the
runs differ only in the number of neurons per layer and the training seed. Data are shared across runs.
"""
import copy

import yaml

from c4n import config

WIDTHS = [256, 512, 1024, 2048, 4096]
SEEDS = [1, 2]
EXTRA = {256: [3, 4], 1024: [3, 4], 4096: [3]}  # added after the first sweep (PLAN addendum e, T4)


def main():
    base = config.load("base")
    out = config.ROOT / "configs" / "sweep"
    out.mkdir(exist_ok=True)
    for w, s in [(w, s) for w in WIDTHS for s in SEEDS] + [(w, s) for w, ss in EXTRA.items() for s in ss]:
        if True:
            c = copy.deepcopy(base)
            name = f"w{w}_s{s}"
            c["model"]["d_ff"] = w
            c["train"]["seed"] = s
            c["train"]["out_dir"] = f"checkpoints/sweep/{name}"
            c["train"]["ckpt_steps"] = [0, 1000, 4000, c["train"]["steps"]]
            c["results_dir"] = f"results/sweep/{name}"
            c["analysis"]["checkpoint"] = f"checkpoints/sweep/{name}/step_{c['train']['steps']:06d}.pt"
            (out / f"{name}.yaml").write_text(f"# generated by scripts/make_sweep.py: d_ff={w}, train seed={s}\n" + yaml.safe_dump(c, sort_keys=False))
    print(f"{len(WIDTHS) * len(SEEDS)} configs in configs/sweep/")


if __name__ == "__main__":
    main()
