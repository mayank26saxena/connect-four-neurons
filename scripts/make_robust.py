"""Write configs/robust/<name>.yaml: single-factor variations of the d_ff 1,024 / seed 1 model (PLAN addendum e, T5-T7)."""
import copy

import yaml

from c4n import config

RUNS = {
    "len32k": {"train.steps": 32000, "train.warmup": 300, "train.ckpt_steps": [0, 32000]},            # T5: 4x training length
    "wd0": {"train.weight_decay": 0.0},                                                               # T6
    "wd1": {"train.weight_decay": 1.0},                                                               # T6
    "dm512_ff1024": {"model.d_model": 512, "model.d_ff": 1024},                                       # T7: ratio 2
    "dm512_ff2048": {"model.d_model": 512, "model.d_ff": 2048},                                       # T7: ratio 4
}


def setp(c, dotted, v):
    *path, last = dotted.split(".")
    for k in path:
        c = c[k]
    c[last] = v


def main():
    base = config.load("base")
    out = config.ROOT / "configs" / "robust"
    out.mkdir(exist_ok=True)
    for name, edits in RUNS.items():
        c = copy.deepcopy(base)
        c["model"]["d_ff"] = 1024
        c["train"]["seed"] = 1
        for k, v in edits.items():
            setp(c, k, v)
        steps = c["train"]["steps"]
        c["train"]["ckpt_steps"] = edits.get("train.ckpt_steps", [0, steps])
        c["train"]["out_dir"] = f"checkpoints/robust/{name}"
        c["results_dir"] = f"results/robust/{name}"
        c["analysis"]["checkpoint"] = f"checkpoints/robust/{name}/step_{steps:06d}.pt"
        (out / f"{name}.yaml").write_text(f"# generated by scripts/make_robust.py: {edits}\n" + yaml.safe_dump(c, sort_keys=False))
    print(f"{len(RUNS)} configs in configs/robust/")


if __name__ == "__main__":
    main()
