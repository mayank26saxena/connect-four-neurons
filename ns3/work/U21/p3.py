# Additive token-mixture approximation built from act minimal pairs (12-ply substitution tests).
BASE = [0.290, 0.341, 0.751, 0.272, 0.064, 0.202, -0.011]
DME = [
    [0, -.188, .211, -.175, -.039, .037, -.001],
    [0, -.377, .102, -.202, -.068, -.012, -.059],
    [0, -.194, -.238, -.221, -.054, -.008, -.045],
    [0, -.265, .063, -.203, -.023, .040, -.141],
    [0, -.190, .108, -.293, -.112, .036, -.100],
    [0, -.191, .052, -.257, -.050, -.196, -.117],
    [0, -.258, -.031, -.346, -.035, -.067, .150],
]
DTH = [
    [-.400, 0, .166, -.209, -.120, -.026, -.041],
    [.072, 0, .184, -.163, -.083, -.008, -.030],
    [.015, 0, -.015, -.232, -.218, -.065, -.053],
    [.051, 0, .176, .107, -.128, .031, .068],
    [.004, 0, .092, -.235, -.149, -.009, -.072],
    [.070, 0, .171, -.154, -.095, -.003, -.006],
    [.123, 0, .117, -.199, -.044, .076, .157],
]

def pred(b):
    L = b.last_col
    if L is None or b.ply < 2:
        return 0.0
    s = 0.0
    for r in range(6):
        for c in range(7):
            v = b.grid[r][c]
            if v == 1:
                s += DME[L][c]
            elif v == 2:
                s += DTH[L][c]
    s -= DTH[L][L]  # the last stone itself is not context
    n = b.ply - 1
    sbase = 3 * DME[L][4] + 2 * DTH[L][5]
    return BASE[L] + 11.0 * s / n - sbase

def fires(b):
    return pred(b) > 0.611

def level(b):
    p = pred(b)
    return max(0, min(9, int((p + 0.2) * 6)))
